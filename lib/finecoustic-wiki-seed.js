function seedContentForTitle(title) {
  const key = String(title || '').trim().toLowerCase();
  return FINEACOUSTIC_WIKI_SEED.find(page => page.title.toLowerCase() === key)?.content || null;
}

/** Strip deprecated wiki copy from stored pages (e.g. removed Cream colour). */
export function patchFinecousticWikiContent(title, content) {
  const key = String(title || '').trim().toLowerCase();
  let next = String(content || '');

  const refreshMarkers = WIKI_REFRESH_MARKERS[key];
  if (refreshMarkers?.some(re => re.test(next))) {
    const fresh = seedContentForTitle(title);
    if (fresh) return fresh;
  }

  if (key === 'design language') {
    next = next.replace(CREAM_COLOUR_LINE, '');
  }

  if (key === 'finecoustic as a brand') {
    if (!/<h2>About us<\/h2>/i.test(next) || /<h2>5W1H<\/h2>/i.test(next)) {
      const fresh = seedContentForTitle(title);
      if (fresh) return fresh;
    }
    if (LEGACY_FANTECH_RELATIONSHIP.test(next)) {
      next = next.replace(LEGACY_FANTECH_RELATIONSHIP, FANTECH_RELATIONSHIP_HTML);
    }
    return next === content ? content : next;
  }

  return next === content ? content : next;
}
